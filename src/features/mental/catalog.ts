export const completedMentalLessons = (ids: string[]) =>
  mentalLessons.filter((l) => ids.includes(l.id)).length;
export function technicalMentalCue(
  mode: Mode,
  previous?: Attempt,
  pressure = false,
) {
  if (previous)
    return successfulAttempt(previous)
      ? "Zachowaj tę samą rutynę."
      : "Reset i następne zadanie.";
  if (pressure || mode === "shoot") return "Ustal cel. Oddech. Rzut.";
  if (mode === "lob") return "Wybierz strefę lądowania i wysokość lotu.";
  if (mode === "boundary") return "Wybierz bezpieczny tor i miejsce lądowania.";
  return "Najpierw wybierz miejsce lądowania.";
}
